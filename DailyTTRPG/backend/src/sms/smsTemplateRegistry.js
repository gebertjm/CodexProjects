const BRAND = 'DailyTTRPG';
const SUPPORT_EMAIL = 'dailyttrpg@gmail.com';

function baseTemplate({
  template_id,
  category,
  description,
  required_variables,
  optional_variables = [],
  body,
  variation_slots = {},
  max_length_guidance = 160,
  options = { allowed: false, required: false, min: 0, max: 0 },
  example_variables,
  example_output,
}) {
  return {
    template_id,
    category,
    description,
    required_variables,
    optional_variables,
    body,
    variation_slots,
    max_length_guidance,
    options,
    example_variables,
    example_output,
  };
}

function withBrand(values = {}) {
  return {
    brand_name: BRAND,
    support_email: SUPPORT_EMAIL,
    ...values,
  };
}

