const templateMap = new Map(SMS_TEMPLATES.map((template) => [template.template_id, template]));

export function getSmsTemplate(templateId) {
  return templateMap.get(templateId) ?? null;
}

export function listSmsTemplates() {
  return SMS_TEMPLATES.map((template) => ({ ...template }));
}

export function listSmsTemplateIds() {
  return SMS_TEMPLATES.map((template) => template.template_id);
}

export function hasSmsTemplate(templateId) {
  return templateMap.has(templateId);
}
